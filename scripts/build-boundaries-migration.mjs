// Turns supabase/data/*.geojson into a migration that loads the city and barangay boundaries.
// Run after refreshing the GeoJSON: `npm run db:boundaries`.
import { readFileSync, writeFileSync } from "node:fs";

const city = JSON.parse(readFileSync("supabase/data/cabanatuan-city.geojson", "utf8"));
const barangays = JSON.parse(readFileSync("supabase/data/cabanatuan-barangays.geojson", "utf8"));

const literal = (value) => (value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const geometry = (g) => `extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson(${literal(JSON.stringify(g))}), 4326))`;

const lines = [
  "-- Generated by scripts/build-boundaries-migration.mjs from supabase/data/. Do not edit by hand.",
  "-- Boundaries: NAMRIA & PSA via OCHA/HDX (COD-AB Philippines), CC BY-IGO 3.0. Barangay codes: PSA PSGC.",
  "",
  "insert into public.city_boundary (id, name, geom) values",
  `  (1, ${literal(city.properties.name)}, ${geometry(city.geometry)})`,
  "on conflict (id) do update set name = excluded.name, geom = excluded.geom;",
  "",
  "insert into public.barangays (name, psgc, geom) values",
  barangays.features
    .map((f) => `  (${literal(f.properties.name)}, ${literal(f.properties.psgc)}, ${geometry(f.geometry)})`)
    .join(",\n"),
  "on conflict (psgc) do update set name = excluded.name, geom = excluded.geom;",
  "",
];

const out = "supabase/migrations/20261018000600_boundaries.sql";
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} (${barangays.features.length} barangays)`);
